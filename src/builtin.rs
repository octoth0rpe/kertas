//! Kertas's built-in documents: Kertas Help, Markdown Syntax, Keyboard
//! Shortcuts, Themes, Release Notes, Licenses and About Kertas.
//!
//! They open as tabs, but they're Kertas's own content, so they're
//! view-only: no caret, no editing, nothing to save.

use std::borrow::Cow;

use gpui::App;

use kertas_editor::help;

use crate::app_settings;
use crate::document_window::DocumentWindow;
use crate::windows;

/// A built-in document.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Builtin {
    Help,
    MarkdownSyntax,
    KeyboardShortcuts,
    Themes,
    ReleaseNotes,
    Licenses,
    About,
}

impl Builtin {
    pub fn title(self) -> &'static str {
        match self {
            Self::Help => "Kertas Help",
            Self::MarkdownSyntax => "Markdown Syntax",
            Self::KeyboardShortcuts => "Keyboard Shortcuts",
            Self::Themes => "Themes",
            Self::ReleaseNotes => "Release Notes",
            Self::Licenses => "Licenses",
            Self::About => "About Kertas",
        }
    }

    pub fn text(self) -> Cow<'static, str> {
        match self {
            Self::Help => include_str!("builtin/help.md").into(),
            Self::MarkdownSyntax => help::markdown_syntax("Kertas").into(),
            // Kertas's own shortcuts, then the editor's.
            Self::KeyboardShortcuts => format!(
                "{}{}",
                include_str!("builtin/shortcuts.md"),
                help::EDITOR_SHORTCUTS
            )
            .into(),
            Self::Themes => help::themes(
                "Kertas",
                &app_settings::themes_folder_in(&crate::config_folder()),
            )
            .into(),
            // The license notices and the library list are generated by
            // scripts/acknowledgements.sh.
            Self::Licenses => include_str!("builtin/licenses.md").into(),
            // The repo's changelog.
            Self::ReleaseNotes => include_str!("../CHANGELOG.md").into(),
            Self::About => include_str!("builtin/about.md")
                .replace("{version}", env!("CARGO_PKG_VERSION"))
                .replace(
                    "{acknowledgements}",
                    include_str!("builtin/acknowledgements.md"),
                )
                .into(),
        }
    }
}

/// Opens `builtin` in a new tab, or switches to it if it's open already.
pub fn open(builtin: Builtin, cx: &mut App) {
    let existing = cx.windows().into_iter().find_map(|window| {
        let window = window.downcast::<DocumentWindow>()?;
        let index = window.read(cx).ok()?.builtin_tab(builtin, cx)?;
        Some((window, index))
    });
    match existing {
        Some((window, index)) => {
            window
                .update(cx, |this, window, cx| {
                    window.activate_window();
                    this.tabs()
                        .update(cx, |tabs, cx| tabs.activate(index, window, cx));
                })
                .ok();
        }
        None => {
            if let Some(window) = windows::open_window(cx, |_, _, _| {}) {
                window
                    .0
                    .update(cx, |this, window, cx| {
                        if let Some(view) = this.tabs().read(cx).active_view().cloned() {
                            this.open_builtin(&view, builtin, window, cx);
                        }
                    })
                    .ok();
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use gpui::Keystroke;
    use kertas_editor::help::shortcut_label;

    #[test]
    fn every_shortcut_is_documented() {
        let document = Builtin::KeyboardShortcuts.text();
        let document = document.as_ref();
        let mut missing = Vec::new();
        let bindings = kertas_editor::key_bindings()
            .into_iter()
            .chain(crate::document_window::key_bindings())
            .chain(kertas_editor::tabs::key_bindings())
            .chain(kertas_editor::zoom::key_bindings())
            .chain(kertas_editor::settings_window::key_bindings());
        for binding in bindings {
            for keystroke in binding.keystrokes() {
                let label = shortcut_label(keystroke.inner());
                // Tabs 2 to 8 are written as a range, "⌘1 … ⌘9".
                let in_tab_range = matches!(
                    label.as_str(),
                    "⌘2" | "⌘3" | "⌘4" | "⌘5" | "⌘6" | "⌘7" | "⌘8"
                );
                if !in_tab_range && !document.contains(&label) {
                    missing.push(label);
                }
            }
        }
        assert!(missing.is_empty(), "not in shortcuts.md: {missing:?}");
    }

    #[test]
    fn themes_documents_every_color() {
        let text = Builtin::Themes.text();
        for &(key, _) in kertas_core::themes::COLORS {
            assert!(text.contains(&format!("| `{key}` |")), "{key}");
        }
        let example = text.split("```toml\n").nth(1).unwrap();
        let example = example.split("```").next().unwrap();
        let (theme, problems) = kertas_core::themes::parse(example).unwrap();
        assert_eq!(theme.name, "My Theme");
        assert_eq!(problems, vec![]);
        assert_eq!(theme.light, kertas_core::themes::kertas().light);
    }

    #[test]
    fn release_notes_cover_this_version() {
        let notes = Builtin::ReleaseNotes.text();
        assert!(notes.starts_with("# Release Notes\n"));
        let version = env!("CARGO_PKG_VERSION");
        assert!(
            notes.contains(&format!("\n## {version} — ")),
            "CHANGELOG.md has a section for {version}"
        );
    }

    #[test]
    fn about_fills_in_its_details() {
        let about = Builtin::About.text();
        assert!(about.contains(concat!("Version ", env!("CARGO_PKG_VERSION"))));
        assert!(about.contains("| gpui |"));
        assert!(!about.contains('{'), "every placeholder is filled in");
        assert!(!about.contains("Permission is hereby granted"));
    }

    #[test]
    fn licenses_has_the_notices() {
        let licenses = Builtin::Licenses.text();
        assert!(licenses.starts_with("# Licenses\n"));
        assert!(licenses.contains(" gpui "), "GPUI is acknowledged");
        assert!(licenses.contains("Copyright (c) The Rust Project Contributors"));
    }

    #[test]
    fn markdown_syntax_links_reach_their_headings() {
        let text = Builtin::MarkdownSyntax.text();
        let model = kertas_core::model::Model::new(&text);
        let mut targets = text.split("](#").skip(1).peekable();
        assert!(targets.peek().is_some(), "it has links within it");
        for target in targets {
            let name = &target[..target.find(')').unwrap()];
            assert!(
                kertas_core::anchors::find(&model, name).is_some(),
                "#{name}"
            );
        }
    }

    #[test]
    fn labels() {
        let label = |text: &str| shortcut_label(&Keystroke::parse(text).unwrap());
        assert_eq!(label("cmd-shift-s"), "⇧⌘S");
        assert_eq!(label("ctrl-shift-tab"), "⌃⇧⇥");
        assert_eq!(label("alt-shift-left"), "⌥⇧←");
        assert_eq!(label("cmd-]"), "⌘]");
    }
}
